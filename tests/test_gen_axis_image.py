"""Generator test for tools/gen_axis_image.py (needs Pillow; skipped otherwise)."""
import base64
import io
import re

import pytest

pytest.importorskip("PIL")

from PIL import Image  # noqa: E402

from tools.gen_axis_image import SRC, build  # noqa: E402

pytestmark = pytest.mark.skipif(not SRC.exists(), reason="source PNG missing")

LINE2 = re.compile(r"^export const AXIS_IMAGE = 'data:image/webp;base64,([A-Za-z0-9+/=]+)';$")


def _payload():
    text = build()
    lines = text.split("\n")
    assert len(lines) == 3 and lines[2] == ""
    assert "\r" not in text
    assert text.endswith("\n")
    assert lines[0].startswith("// GENERATED by tools/gen_axis_image.py")
    m = LINE2.match(lines[1])
    assert m, "line 2 does not match the module format"
    return base64.b64decode(m.group(1), validate=True)


def test_module_structure_and_webp_header():
    raw = _payload()
    assert raw[:4] == b"RIFF"
    assert raw[8:12] == b"WEBP"


def test_webp_decodes_to_1024x683():
    img = Image.open(io.BytesIO(_payload()))
    assert img.format == "WEBP"
    assert img.size == (1024, 683)


def test_decoded_size_budget():
    assert 40_000 <= len(_payload()) <= 250_000
