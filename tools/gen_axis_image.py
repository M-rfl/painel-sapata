"""Re-encode the axis PNG to WebP and write site/js/app/axisimage.js (one line, LF). Dev tool; needs Pillow."""
import base64
import io
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".planning/phases/16-axis-orientation-popup/orientacao-eixos.png"
OUT = ROOT / "site/js/app/axisimage.js"
WIDTH, QUALITY = 1024, 78


def _webp_bytes(src: Path) -> bytes:
    with Image.open(src) as im:
        im = im.convert("RGB")
        w, h = im.size
        im = im.resize((WIDTH, round(h * WIDTH / w)), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, format="WEBP", quality=QUALITY, method=6)
    return buf.getvalue()


def build(src: Path = SRC) -> str:
    raw = _webp_bytes(src)
    uri = "data:image/webp;base64," + base64.b64encode(raw).decode("ascii")
    return (
        "// GENERATED by tools/gen_axis_image.py from orientacao-eixos.png. Do not edit.\n"
        f"export const AXIS_IMAGE = '{uri}';\n"
    )


if __name__ == "__main__":
    text = build()
    # write_bytes, not write_text: avoid CRLF translation on Windows.
    OUT.write_bytes(text.encode("utf-8"))
    decoded = len(_webp_bytes(SRC))
    print(f"wrote {OUT} (decoded {decoded} bytes, file {len(text)} bytes)")
